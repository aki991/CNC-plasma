import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { parseDxf } from '../../src/geometry/dxf';

test('Podesivo podnožje spaja betonske stubove i menja meru lima',async({page})=>{
  await page.goto('/projektovanje-ograda');
  await page.getByRole('button',{name:'Novi projekat',exact:true}).click();
  await page.getByRole('combobox',{name:'Podrazumevani tip'}).selectOption('concrete');
  await page.getByRole('spinbutton',{name:'Visina podnožja (mm)',exact:true}).fill('200');
  const concrete=page.locator('.fence-concrete');
  const outline='M0 0V-1280H100V-200H1900V-1280H2000V0Z';
  await expect(concrete).toHaveAttribute('d',outline);
  await expect(page.locator('.fence-post.concrete .fence-post-body')).toHaveCount(0);
  await expect(page.locator('.fence-projectbar [role=status]')).toHaveText('Automatski sačuvano');
  await page.reload();
  await expect(concrete).toHaveAttribute('d',outline);
  await page.getByRole('button',{name:/^Segment 1 .*mm$/}).click();
  const plinth=page.getByRole('spinbutton',{name:'Visina podnožja segmenta (mm)',exact:true});
  await expect(plinth).toHaveValue('200');
  await expect(page.getByRole('spinbutton',{name:'Od podnožja (mm)',exact:true})).toHaveValue('80');
  await plinth.fill('250');
  await expect(concrete).toHaveAttribute('d',outline.replace('V-200H','V-250H'));
  await page.getByRole('button',{name:'Primeni visinu podnožja projekta'}).click();
  await expect(concrete).toHaveAttribute('d',outline);
  await expect(page.locator('.fence-leaf-box')).toHaveAttribute('height','920');
  await page.getByRole('button',{name:'Generiši DXF za sečenje'}).click();
  const file=page.waitForEvent('download');
  await page.locator('.fence-result').getByRole('button',{name:/Preuzmi .*\.dxf/}).click();
  const geometry=parseDxf(await readFile((await (await file).path())!,'utf8'));
  expect(geometry).toMatchObject({valid:true,unit:4,shape:{width:1780,height:920}});
});

test('Brisanje segmenta, kapije i stuba uz potvrdu i poništavanje',async({page})=>{
  await page.goto('/projektovanje-ograda');
  await page.getByRole('button',{name:'Novi projekat',exact:true}).click();
  const tree=page.locator('.fence-tree');
  const spans=tree.locator('.span');
  const posts=page.locator('.fence-post');
  const remove=page.getByRole('button',{name:'Potvrdi brisanje',exact:true});
  await tree.getByRole('button',{name:/^Segment 1/}).click();
  await page.getByRole('button',{name:'Obriši segment',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('granični stub 2');
  await page.getByRole('button',{name:'Otkaži',exact:true}).click();
  await expect(spans).toHaveCount(1);
  await page.getByRole('button',{name:'Obriši segment',exact:true}).click();
  await remove.click();
  await expect(spans).toHaveCount(0);
  await expect(posts).toHaveCount(1);
  await expect(page.getByRole('button',{name:'Generiši DXF za sečenje'})).toBeDisabled();
  await page.getByRole('button',{name:'Poništi izmenu',exact:true}).click();
  await expect(spans).toHaveCount(1);

  await page.getByRole('button',{name:'Dodaj kapiju',exact:true}).click();
  await page.getByRole('button',{name:'Umetni kapiju',exact:true}).click();
  await page.getByRole('button',{name:'Obriši kapiju',exact:true}).click();
  await remove.click();
  await expect(spans).toHaveCount(1);
  await expect(posts).toHaveCount(2);

  await page.getByRole('button',{name:'Dodaj stub',exact:true}).click();
  await expect(posts).toHaveCount(3);
  await page.getByRole('button',{name:'Obriši stub',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('susedna segmenta se spajaju');
  await remove.click();
  await expect(posts).toHaveCount(2);

  await tree.getByRole('button',{name:/^Stub 1/}).click();
  await page.getByRole('button',{name:'Obriši stub',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('Stub 1 i Segment 1');
  await remove.click();
  await tree.getByRole('button',{name:/^Stub 1/}).click();
  await page.getByRole('button',{name:'Obriši stub',exact:true}).click();
  await remove.click();
  await expect(posts).toHaveCount(0);
  await expect(page.locator('.fence-projectbar [role=status]')).toHaveText('Automatski sačuvano');
  await page.reload();
  await expect(page.getByText('Dodajte stub, segment ili kapiju.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Dodaj segment',exact:true}).click();
  await expect(spans).toHaveCount(1);
  await expect(posts).toHaveCount(2);
});

test('Ograda → validan DXF → posao → nesting → kalkulacija → ponuda', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error=>errors.push(error.message));
  await page.goto('/');
  await page.getByRole('link',{name:'Projektovanje ograda',exact:true}).click();
  await page.getByRole('button',{name:'Novi projekat',exact:true}).click();
  await expect(page.getByLabel('Naziv projekta')).toBeVisible();
  const projectUrl=page.url();
  await page.getByLabel('Naziv projekta').fill('Ograda za radionicu');
  await page.getByRole('combobox',{name:'Kupac ograde'}).selectOption({label:'Petrović d.o.o.'});
  await page.getByRole('button',{name:/1 seg\./}).click();
  await page.getByRole('spinbutton',{name:'Broj segmenata',exact:true}).fill('3');
  await page.getByRole('button',{name:'Primeni broj segmenata'}).click();
  await expect(page.locator('.fence-post')).toHaveCount(4);
  await page.getByRole('button',{name:'Promeni dužinu',exact:true}).click();
  await page.getByRole('spinbutton',{name:'Nova ukupna dužina (mm)'}).fill('5500');
  await page.getByRole('button',{name:'Primeni preraspodelu'}).click();
  const total=page.locator('.fence-projecttitle small');
  await expect(total).toContainText('5.500 mm');
  await page.getByRole('button',{name:'Poništi izmenu'}).click();
  await expect(total).toContainText('5.800 mm');
  await page.getByRole('button',{name:'Ponovi izmenu'}).click();
  await expect(total).toContainText('5.500 mm');
  await expect(page.locator('.fence-projectbar [role=status]')).toHaveText('Automatski sačuvano');
  await page.reload();
  await expect(page.getByLabel('Naziv projekta')).toHaveValue('Ograda za radionicu');
  await expect(page.locator('.fence-post')).toHaveCount(4);
  await expect(total).toContainText('5.500 mm');

  const canvas=page.locator('.fence-svg');
  const initialView=await canvas.getAttribute('viewBox');
  await page.getByRole('button',{name:'Uvećaj prikaz ograde'}).click();
  await expect(canvas).not.toHaveAttribute('viewBox',initialView!);
  await page.getByRole('button',{name:'Prikaži celu ogradu'}).click();
  await expect(canvas).toHaveAttribute('viewBox',initialView!);
  await page.getByRole('button',{name:'Segment 2 · prikaz',exact:true}).click();
  await expect(page.getByRole('spinbutton',{name:'Svetla širina (mm)'})).toHaveValue('1700');
  await page.getByRole('button',{name:'Parametri projekta',exact:true}).click();

  await page.getByRole('button',{name:'Generiši DXF za sečenje'}).click();
  const panel=page.locator('.fence-result tbody tr');
  await expect(panel).toHaveCount(1);
  await expect(panel).toContainText('1.680 mm × 1.120 mm');
  await expect(panel.locator('td').nth(3)).toHaveText('3');
  const file=page.waitForEvent('download');
  await panel.getByRole('button',{name:/Preuzmi .*\.dxf/}).click();
  const result=parseDxf(await readFile((await (await file).path())!,'utf8'));
  expect(result).toMatchObject({valid:true,unit:4,shape:{width:1680,height:1120}});
  expect(result.shape.depths).toContain(1);
  await page.getByRole('button',{name:'Zatvori obaveštenje'}).click();
  await page.screenshot({path:'test-results/screenshots/1920x1080/06-projektovanje-ograda.png',animations:'disabled'});

  await page.getByRole('button',{name:'Pošalji u nesting',exact:true}).click();
  await page.getByRole('button',{name:'Otvori nesting',exact:true}).click();
  await expect(page).toHaveURL(/\/nesting\/P-1070$/);
  await page.getByRole('button',{name:'Optimizuj raspored'}).click();
  await expect(page.getByText('Sačuvan raspored')).toBeVisible();
  await expect(page.getByText('3 / 0 kom')).toBeVisible();
  await page.getByRole('link',{name:'Nastavi na kalkulaciju'}).click();
  await page.getByText('Mere ograde · Ograda za radionicu').click();
  await expect(page.getByText('Paneli / limeni delovi')).toBeVisible();
  await page.getByText(/Probijanje, otpad i ostale stavke/).click();
  await expect(page.getByRole('spinbutton',{name:'Količina – Stubovi',exact:true})).toHaveValue('4');
  await page.getByRole('button',{name:'Kreiraj ponudu'}).click();
  await expect(page.getByRole('dialog')).toContainText('Ponuda je kreirana');

  await page.goto(projectUrl);
  await expect(page.getByRole('link',{name:'Posao P-1070'})).toBeVisible();
  await expect(page.locator('.fence-result tbody tr')).toHaveCount(1);
  expect(errors).toEqual([]);
});

